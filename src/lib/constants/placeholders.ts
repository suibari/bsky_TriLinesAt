export function getRandomPlaceholders(count: number, locale: string = 'ja'): string[] {
  // Use a copy to avoid mutating original
  const genres = [...PLACEHOLDER_GENRES];
  const results: string[] = [];

  const lang = locale.startsWith('en') ? 'en' : 'ja';

  for (let i = 0; i < count; i++) {
    if (genres.length === 0) break;

    // Pick a random genre
    const genreIndex = Math.floor(Math.random() * genres.length);
    const genre = genres[genreIndex];

    // Pick a random question from that genre
    const questionObj =
      genre.questions[Math.floor(Math.random() * genre.questions.length)];

    results.push(questionObj[lang]);

    // Remove the used genre to ensure diversity
    genres.splice(genreIndex, 1);
  }

  // If we couldn't get enough
  while (results.length < count) {
    results.push(lang === 'en' ? "Write one good thing in one line" : "よかったことを1行で");
  }

  return results;
}
